//! End-to-end tests of the CLI against a real `YubiKey` (PIV, through ykcs11), read-write.
//!
//! Needs `CAKEYS_TEST_YUBIKEY_MODULE` (path to libykcs11.so), `CAKEYS_TEST_YUBIKEY_PIN` (path to
//! a file holding the PIV PIN) and `CAKEYS_TEST_YUBIKEY_MGM` (path to a file holding the admin
//! credential: the PIV management key in hex — which logs in without spending a PIN retry — or
//! the PIN on a PIN-protected-management-key device). The CLI uses it only for the SO steps that
//! generate keys, then logs the user back in. Tests are skipped when any is unset — they never
//! run in the Nix build — and the secrets are only ever read by the CLI from these paths: never
//! printed, never stored, never committed.
//!
//! The tests own the top retired slots, one key type each, and never touch any other slot:
//!
//! | slot | `CKA_ID` | what |
//! |---|---|---|
//! | 95 | 18 | P-256, `pop-sign` (the original read-write test) |
//! | 94 | 17 | the write probe's scratch slot (`scratchId`): replaced by every probe run |
//! | 93 | 16 | P-384, `pop-ecdh` |
//! | 92 | 15 | Ed25519, `pop-sign` (generated by name: profiles/modules/ykcs11/2.7.toml) |
//! | 91 | 14 | RSA-2048, `pop-decrypt` |
//! | 90 | 13 | RSA-3072, `pop-sign` |
//!
//! ykcs11 cannot erase a PIV key (its `C_DestroyObject` clears only the slot's certificate), so
//! `delete` is refused and each test adopts whatever a previous run left in its slot;
//! `ykman piv keys delete <slot>` empties one to exercise generation again. Every CLI run is
//! bounded in time: a touch or a PIN prompt would hang the run and fail the test instead of
//! waiting for a user.

use cryptoki::context::{CInitializeArgs, CInitializeFlags, Pkcs11};
use std::fmt::Write as _;
use std::path::PathBuf;
use std::process::{Command, Output};
use std::time::{Duration, Instant};

const BIN: &str = env!("CARGO_BIN_EXE_cakeys");
/// `YubiKey` operations are interactive hardware calls in the worst case; none of the tested ones
/// needs presence, and the bound turns a policy change (touch) into a test failure.
const RUN_LIMIT: Duration = Duration::from_secs(60);
/// The write probe generates every curve and RSA size it tries in one run (74 s measured on a
/// `YubiKey` 5.7.4, RSA-4096 included).
const PROBE_LIMIT: Duration = Duration::from_secs(300);

struct Env {
    dir: PathBuf,
    module: String,
    pin: String,
    mgm: String,
}

fn env(name: &str) -> Option<Env> {
    let (Ok(module), Ok(pin), Ok(mgm)) = (
        std::env::var("CAKEYS_TEST_YUBIKEY_MODULE"),
        std::env::var("CAKEYS_TEST_YUBIKEY_PIN"),
        std::env::var("CAKEYS_TEST_YUBIKEY_MGM"),
    ) else {
        eprintln!("skipping {name}: CAKEYS_TEST_YUBIKEY_MODULE, _PIN and _MGM (file paths) not all set");
        return None;
    };
    Some(Env { dir: workdir(name), module, pin, mgm })
}

/// A fresh directory `name` under the integration tests' tmpdir.
fn workdir(name: &str) -> PathBuf {
    let dir = PathBuf::from(env!("CARGO_TARGET_TMPDIR")).join(name);
    let _ = std::fs::remove_dir_all(&dir);
    std::fs::create_dir_all(&dir).unwrap();
    dir
}

/// One key the read-write tests generate, attest and prove, in a slot of its own.
struct Case {
    name: &'static str,
    /// The slot's `CKA_ID` (ykcs11's table: 13-18 are retired slots 90-95).
    id: &'static str,
    /// The `[objects.<name>]` body after the class.
    object: &'static str,
    /// The spec's policy attributes, as an inline table body.
    attributes: &'static str,
    /// The possession proof the spec asks for; the lock records it.
    binding: &'static str,
}

const P256: Case = Case {
    name: "rw-test",
    id: "18",
    object: "keyType = \"CKK_EC\"\ncurve = \"secp256r1\"",
    attributes: "CKA_SIGN = true",
    binding: "pop-sign",
};

/// The other key types this `YubiKey` generates (profiles/modules/ykcs11/2.7.toml), each with
/// the proof that exercises a different path: ECDH into ykcs11's extractable-only secret, an
/// Edwards curve it takes only by name, RSA-OAEP decryption, a larger RSA modulus.
const KEY_TYPES: [Case; 4] = [
    // ykcs11 reports CKA_DERIVE false on every key, from a fixed table, while its keys derive
    // (`derive.key-attribute` in the profile): the provider repairs it, and the proof shows it.
    Case {
        name: "p384-ecdh",
        id: "16",
        object: "keyType = \"CKK_EC\"\ncurve = \"secp384r1\"",
        attributes: "CKA_DERIVE = true",
        binding: "pop-ecdh",
    },
    Case {
        name: "ed25519",
        id: "15",
        object: "keyType = \"CKK_EC_EDWARDS\"\ncurve = \"edwards25519\"",
        attributes: "CKA_SIGN = true",
        binding: "pop-sign",
    },
    Case {
        name: "rsa2048-decrypt",
        id: "14",
        object: "keyType = \"CKK_RSA\"\nmodulusBits = 2048",
        attributes: "CKA_DECRYPT = true",
        binding: "pop-decrypt",
    },
    Case {
        name: "rsa3072",
        id: "13",
        object: "keyType = \"CKK_RSA\"\nmodulusBits = 3072",
        attributes: "CKA_SIGN = true",
        binding: "pop-sign",
    },
];

impl Env {
    /// The token with both credentials and the probe's scratch slot (`extra` added to it), and
    /// one spec per case: its key generated on first use into the case's slot, attested.
    fn config(&self, cases: &[&Case], extra: &str) {
        let mut text = format!(
            "[tokens.yubikey]\nmodule = \"{m}\"\ntokenLabel = \"{label}\"\npinFile = \"{pin}\"\n\
             mgmKeyFile = \"{mgm}\"\n{extra}\n",
            m = self.module,
            label = yubikey_label(&self.module),
            pin = self.pin,
            mgm = self.mgm,
        );
        for c in cases {
            let _ = write!(
                text,
                "\n[objects.{n}]\nclass = \"CKO_PRIVATE_KEY\"\n{object}\n\n\
                 [specs.{n}-yubikey]\nobject = \"{n}\"\nattributes = {{ {attributes} }}\n\
                 tokens.yubikey = {{ locator = {{ CKA_ID = \"{id}\" }}, autoCreate = true, attestation = true, \
                 binding = \"{binding}\" }}\n",
                n = c.name,
                object = c.object,
                attributes = c.attributes,
                id = c.id,
                binding = c.binding,
            );
        }
        std::fs::write(self.dir.join("keys.toml"), text).unwrap();
    }

    fn lock(&self) -> toml::Value {
        toml::from_str(&std::fs::read_to_string(self.dir.join("keys.lock")).unwrap()).unwrap()
    }

    fn km(&self, args: &[&str]) -> Output {
        self.km_within(args, RUN_LIMIT)
    }

    /// Run the CLI bounded in time: a touch or PIN prompt fails the test instead of hanging it.
    fn km_within(&self, args: &[&str], limit: Duration) -> Output {
        let mut child = Command::new(BIN)
            .env_remove("NIX_BUILD_TOP")
            .arg("--config")
            .arg(self.dir.join("keys.toml"))
            .args(args)
            .stdout(std::process::Stdio::piped())
            .stderr(std::process::Stdio::piped())
            .spawn()
            .unwrap();
        let started = Instant::now();
        loop {
            if let Some(status) = child.try_wait().unwrap() {
                // The child is done; the pipes still hold (and now end) its output.
                let mut stdout = Vec::new();
                let mut stderr = Vec::new();
                if let Some(mut p) = child.stdout.take() {
                    std::io::Read::read_to_end(&mut p, &mut stdout).unwrap();
                }
                if let Some(mut p) = child.stderr.take() {
                    std::io::Read::read_to_end(&mut p, &mut stderr).unwrap();
                }
                eprintln!(
                    "$ cakeys {}\n  exit={:?}\n  stdout={}\n  stderr={}",
                    args.join(" "),
                    status.code(),
                    String::from_utf8_lossy(&stdout).trim(),
                    String::from_utf8_lossy(&stderr).trim()
                );
                return Output { status, stdout, stderr };
            }
            if started.elapsed() > limit {
                let _ = child.kill();
                let _ = child.wait();
                panic!(
                    "cakeys {} did not finish within {limit:?}: user presence (touch or PIN) needed?",
                    args.join(" ")
                );
            }
            std::thread::sleep(Duration::from_millis(20));
        }
    }

    /// First use, record, verify, refused delete and idempotent re-realise of `c`: the key is
    /// generated (or adopted from an earlier run) in its slot, attested, its possession proven
    /// by `c.binding` — no touch, no prompt — and it keeps its identity throughout.
    fn lifecycle(&self, c: &Case) {
        let spec = format!("{}-yubikey", c.name);
        let r = ["realise", &spec, "--token", "yubikey", "--no-update-lock"];
        let record = ["realise", &spec, "--token", "yubikey", "--update-lock"];

        // First use: generated (SO login) or adopted, and identified; nothing is locked yet.
        let first = self.km(&r);
        assert_eq!(code(&first), 10, "{}: {}", c.name, String::from_utf8_lossy(&first.stderr));
        let got = String::from_utf8_lossy(&first.stderr)
            .lines()
            .find_map(|l| l.trim_start().strip_prefix("got:"))
            .map(str::trim)
            .expect("a got: hash")
            .to_owned();
        assert!(got.starts_with("sha256-"), "{got}");

        // Record it: the proof and the attestation ran in the user session, and are recorded.
        let recorded = self.km(&record);
        assert_eq!(code(&recorded), 0, "{}: {}", c.name, String::from_utf8_lossy(&recorded.stderr));
        let lock = self.lock();
        let real = &lock["realisations"][spec.as_str()]["yubikey"];
        assert_eq!(real["binding"].as_str(), Some(c.binding), "{}: possession proven, not asserted", c.name);
        assert_eq!(real["attestation"]["kind"].as_str(), Some("yubico-piv"), "{}: generated on device", c.name);
        assert!(real["attestation"]["id"].as_str().is_some_and(|id| id.starts_with("sha256-")));
        assert!(lock["objects"][c.name]["ids"].get("piv-attestation").is_none(), "the attestation is per realisation");
        assert_eq!(real["object"].as_str(), Some(c.name));
        assert_eq!(lock["objects"][c.name]["ids"]["rfc7093m4"].as_str(), Some(got.as_str()), "the first-use id");

        // Verify in a fresh process: the proof of possession runs again, unattended.
        let verify = ["verify", &spec, "--token", "yubikey"];
        let verified = self.km(&verify);
        assert_eq!(code(&verified), 0, "{}: {}", c.name, String::from_utf8_lossy(&verified.stderr));

        // Delete is refused: ykcs11 would clear only the slot's certificate and report success
        // while the key stays. Nothing changes — the realisation stays and still verifies.
        let deleted = self.km(&["delete", &spec, "--token", "yubikey", "--update-lock"]);
        assert_eq!(code(&deleted), 15, "{}: {}", c.name, String::from_utf8_lossy(&deleted.stderr));
        assert!(String::from_utf8_lossy(&deleted.stderr).contains("ykman piv keys delete"));
        assert!(self.lock()["realisations"][spec.as_str()]["yubikey"].is_table(), "the realisation stays");
        assert_eq!(code(&self.km(&verify)), 0);

        // Re-realising is idempotent: the same key, the same id, nothing generated.
        let again = self.km(&record);
        assert_eq!(code(&again), 0, "{}: {}", c.name, String::from_utf8_lossy(&again.stderr));
        assert!(!String::from_utf8_lossy(&again.stderr).contains("created"), "nothing generated");
        assert_eq!(self.lock()["objects"][c.name]["ids"]["rfc7093m4"].as_str(), Some(got.as_str()), "same identity");
    }
}

/// The label of the first `YubiKey` the module sees, so the config names the right token.
fn yubikey_label(module: &str) -> String {
    let ctx = Pkcs11::new(module).unwrap();
    ctx.initialize(CInitializeArgs::new(CInitializeFlags::OS_LOCKING_OK)).unwrap();
    let slot = ctx
        .get_slots_with_token()
        .unwrap()
        .into_iter()
        .find(|s| ctx.get_token_info(*s).unwrap().model().starts_with("YubiKey"))
        .unwrap();
    ctx.get_token_info(slot).unwrap().label().to_string()
}

fn code(o: &Output) -> i32 {
    o.status.code().unwrap()
}

/// Whether this build's cryptoki has the Nix patches the probe needs to write or judge a
/// profile (an unpatched one drops mechanisms it cannot name); a cargo build here has them only
/// in the Nix build. By hand: `nix build .#cakeys`, then `result/bin/cakeys probe ...`.
fn patched(what: &str) -> bool {
    let patched = std::os::raw::c_ulong::from(cryptoki::object::KeyType::SHA384_HMAC) == 0x2c;
    if !patched {
        eprintln!("skipping {what}: this build's cryptoki is unpatched");
    }
    patched
}

/// Read-write on real hardware: generate into the P-256 slot under the SO (management-key)
/// credential, back in the user session attest it and prove possession by signing (no touch, no
/// prompt), record, verify; `delete` is refused (15) because ykcs11 would leave the key in the
/// slot, so the realisation stays and verifies.
#[test]
fn rw_lifecycle_generates_attests_proves_and_refuses_delete_without_touch() {
    let Some(e) = env("yubikey_rw") else { return };
    e.config(&[&P256], "");
    e.lifecycle(&P256);
}

/// Every other key type the device generates, each proven the way its spec asks: ECDH through
/// ykcs11's extractable-only derivation (it refuses a sealed secret and has no HMAC), Ed25519
/// generated by curve name (ykcs11 refuses the OID), RSA-OAEP decryption, and RSA-3072.
#[test]
fn rw_key_types_generate_attest_and_prove_each_way_without_touch() {
    let Some(e) = env("yubikey_key_types") else { return };
    e.config(&KEY_TYPES.iter().collect::<Vec<_>>(), "");
    for c in &KEY_TYPES {
        e.lifecycle(c);
    }
    // The ECDH key's recorded policy is the repaired one: what the key does.
    let lock = e.lock();
    assert_eq!(lock["realisations"]["p384-ecdh-yubikey"]["yubikey"]["policy"]["CKA_DERIVE"].as_bool(), Some(true));
}

/// The committed ykcs11/2.7 profile is probe output (docs/PROVIDERS.md phase 3): a fresh write
/// probe in the scratch slot conforms, and regenerating the file changes no byte — its
/// [migration] claims and [manual] findings preserved. A slot holding anything but ykcs11's own
/// placeholder is refused before anything is written (the guard's unit test covers the
/// certificate rules: crates/ykcs11/src/lib.rs). Another firmware, or a device not in
/// FIPS-approved mode, drifts by design (exit 15, the rows named): probe it and record a new
/// pair.
#[test]
fn the_write_probe_conforms_and_regenerates_the_committed_profile() {
    let Some(e) = env("yubikey_write_probe") else { return };
    if !patched("the ykcs11/2.7 write probe") {
        return;
    }
    e.config(&[], "scratchId = \"17\"");
    let probe = e.km_within(&["probe", "--token", "yubikey", "--write", "--diff", "ykcs11/2.7"], PROBE_LIMIT);
    assert_eq!(code(&probe), 0, "{}", String::from_utf8_lossy(&probe.stderr));
    let committed = concat!(env!("CARGO_MANIFEST_DIR"), "/../../profiles/modules/ykcs11/2.7.toml");
    let copy = e.dir.join("profile.toml");
    std::fs::copy(committed, &copy).unwrap();
    let out = copy.to_str().unwrap();
    let args = ["probe", "--token", "yubikey", "--write", "--diff", "ykcs11/2.7", "--out", out];
    assert_eq!(code(&e.km_within(&args, PROBE_LIMIT)), 0);
    assert!(
        std::fs::read(&copy).unwrap() == std::fs::read(committed).unwrap(),
        "profiles/modules/ykcs11/2.7.toml is not what the probe generates: regenerate it with `cakeys \
         probe --token <yk> --write --diff ykcs11/2.7 --out profiles/modules/ykcs11/2.7.toml`, and \
         put hand findings in [manual]"
    );
}

/// The read-only probe of the device here (docs/PROVIDERS.md D10): ykcs11/2.7's match keys,
/// advertisement and reported RSA range are what this `YubiKey` shows, and the write probes are
/// refused without a scratch slot — `scratch = true` cannot mark a device that holds real keys
/// beside it. Needs only `CAKEYS_TEST_YUBIKEY_MODULE`: no PIN, nothing written; the diff only
/// with the patched cryptoki (the Nix build's).
#[test]
fn the_read_only_probe_conforms() {
    let Ok(module) = std::env::var("CAKEYS_TEST_YUBIKEY_MODULE") else {
        eprintln!("skipping the_read_only_probe_conforms: CAKEYS_TEST_YUBIKEY_MODULE not set");
        return;
    };
    let dir = workdir("yubikey-probe");
    std::fs::write(
        dir.join("keys.toml"),
        format!(
            "[tokens.yubikey]\nmodule = \"{module}\"\ntokenLabel = \"{}\"\nscratch = true\n",
            yubikey_label(&module)
        ),
    )
    .unwrap();
    // No credentials: the read-only probe needs none, and the write probes must not get far.
    let e = Env { dir, module, pin: String::new(), mgm: String::new() };
    let write = e.km(&["probe", "--token", "yubikey", "--write"]);
    assert_eq!(code(&write), 17);
    assert!(String::from_utf8_lossy(&write.stderr).contains("Security Officer"));
    assert!(String::from_utf8_lossy(&write.stderr).contains("scratchId"));
    if !patched("the ykcs11/2.7 read-only diff") {
        return;
    }
    let out = e.km(&["probe", "--token", "yubikey", "--diff", "ykcs11/2.7"]);
    assert_eq!(code(&out), 0, "{}", String::from_utf8_lossy(&out.stderr));
}
